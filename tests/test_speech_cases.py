"""Numbers agree with the preposition and the word after them (owner, 2026-11-17)."""
import pytest

from brief.speech import spell_numbers


@pytest.mark.parametrize("text, spoken", [
    ("наразі відомо про 31 загиблого", "наразі відомо про тридцять одного загиблого"),
    ("про 2 загиблих", "про двох загиблих"),
    ("з 21 пораненим", "з двадцятьма одним пораненим"),
    ("з 5 областей", "з п'яти областей"),
    ("у 3 областях", "у трьох областях"),
    ("до 12 людей", "до дванадцяти людей"),
    ("серед 4 загиблих", "серед чотирьох загиблих"),
    ("із 172 поранених", "із ста сімдесяти двох поранених"),
    ("про 21 жінку", "про двадцять одну жінку"),
    ("від 14 до 20 листопада", "від чотирнадцятого до двадцятого листопада"),
    ("з 2 до 4 градусів", "з двох до чотирьох градусів"),
    ("загинули 72 людини", "загинули сімдесят дві людини"),
    ("31 людину поранено", "тридцять одну людину поранено"),
    ("у 2026 році", "у дві тисячі двадцять шостому році"),
])
def test_number_case(text, spoken):
    assert spell_numbers(text) == spoken
